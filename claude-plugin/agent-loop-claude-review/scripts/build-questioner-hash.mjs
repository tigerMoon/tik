#!/usr/bin/env node

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';

const repoRoot = path.resolve(new URL('../../..', import.meta.url).pathname);
const sourcePath = path.join(repoRoot, 'packages', 'shared', 'src', 'utils', 'questioner-hash.ts');
const outputPath = path.join(
  repoRoot,
  'claude-plugin',
  'agent-loop-claude-review',
  'scripts',
  '_generated',
  'questioner-hash.mjs',
);

const source = await readFile(sourcePath, 'utf-8');
const transpiled = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.ES2022,
    target: ts.ScriptTarget.ES2022,
    importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
    removeComments: false,
  },
  fileName: sourcePath,
});

const banner = [
  '// Generated by scripts/build-questioner-hash.mjs from packages/shared/src/utils/questioner-hash.ts.',
  '// Do not edit by hand; run `node claude-plugin/agent-loop-claude-review/scripts/build-questioner-hash.mjs`.',
  '',
].join('\n');

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${banner}${transpiled.outputText.trim()}\n`, 'utf-8');
